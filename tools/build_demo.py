def storydata(name, passages, pid0=1, pos=None):
    pos = pos or POS
    names = list(passages)
    out = [f'<tw-storydata name="{html.escape(name)}" startnode="1" creator="Twine" creator-version="2.6.2" '
           f'format="Harlowe" format-version="3.3.8" ifid="{str(uuid.uuid5(uuid.NAMESPACE_URL, name)).upper()}" '
           f'options="" tags="" zoom="1" hidden>'
           '<style role="stylesheet" id="twine-user-stylesheet" type="text/twine-css"></style>'
           '<script role="script" id="twine-user-script" type="text/twine-javascript"></script>']
    for i, n in enumerate(names, 1):
        x, y = pos[n]
        out.append(f'<tw-passagedata pid="{i}" name="{html.escape(n)}" tags="" position="{x},{y}" size="100,100">'
                   f'{html.escape(passages[n], quote=False)}</tw-passagedata>')
    out.append('</tw-storydata>')
    return "".join(out)

def page(blocks, title):
    return ('<!DOCTYPE html><html><head><meta charset="utf-8"><title>' + html.escape(title) + '</title></head><body>\n'
            + "\n".join(blocks) + '\n</body></html>\n')

